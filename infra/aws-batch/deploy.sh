#!/usr/bin/env bash
# Create/update the e2e AWS Batch stack and write infra/aws-batch/e2e.env.
#
# Usage: infra/aws-batch/deploy.sh --vpc-id vpc-... --subnets subnet-a,subnet-b \
#            [--prefix agent-rnaseq-e2e] [--max-vcpus 16] [--on-demand] [--region us-east-1]
# Requires: aws CLI v2 with credentials allowed to create S3/ECR/IAM/Batch/EC2 SG resources.
# Cost: nothing while idle (compute scales to 0); S3/ECR storage is billed until teardown.sh.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
PREFIX=agent-rnaseq-e2e MAX_VCPUS=16 SPOT=true REGION="${AWS_DEFAULT_REGION:-us-east-1}"
VPC_ID="" SUBNETS=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --vpc-id) VPC_ID="$2"; shift 2 ;;
    --subnets) SUBNETS="$2"; shift 2 ;;
    --prefix) PREFIX="$2"; shift 2 ;;
    --max-vcpus) MAX_VCPUS="$2"; shift 2 ;;
    --on-demand) SPOT=false; shift ;;
    --region) REGION="$2"; shift 2 ;;
    *) echo "unknown option $1" >&2; exit 2 ;;
  esac
done
[[ -n "$VPC_ID" && -n "$SUBNETS" ]] || { echo "--vpc-id and --subnets are required" >&2; exit 2; }
command -v aws >/dev/null || { echo "aws CLI v2 not found" >&2; exit 1; }

STACK="${PREFIX}"
echo "Deploying stack ${STACK} in ${REGION} (account $(aws sts get-caller-identity --query Account --output text))"
aws cloudformation deploy --region "$REGION" --stack-name "$STACK" \
  --template-file "${HERE}/batch-stack.yaml" --capabilities CAPABILITY_IAM \
  --parameter-overrides Prefix="$PREFIX" VpcId="$VPC_ID" SubnetIds="$SUBNETS" \
      MaxvCpus="$MAX_VCPUS" UseSpot="$SPOT" \
  --tags Project="$PREFIX"

out() { aws cloudformation describe-stacks --region "$REGION" --stack-name "$STACK" \
  --query "Stacks[0].Outputs[?OutputKey=='$1'].OutputValue" --output text; }

cat > "${HERE}/e2e.env" <<ENV
# generated by deploy.sh — sourced by build_push_tools_image.sh, run_e2e.sh, teardown.sh
export AWS_DEFAULT_REGION=${REGION}
export E2E_STACK=${STACK}
export S3_ARTIFACT_BUCKET=$(out BucketName)
export AWS_BATCH_JOB_QUEUE=$(out JobQueueArn)
export E2E_TOOLS_REPOSITORY=$(out ToolsRepositoryUri)
export E2E_WORKER_POLICY_ARN=$(out WorkerPolicyArn)
ENV
echo "Wrote ${HERE}/e2e.env"
echo "Attach \$E2E_WORKER_POLICY_ARN to the identity that runs the worker if it is not an admin."
